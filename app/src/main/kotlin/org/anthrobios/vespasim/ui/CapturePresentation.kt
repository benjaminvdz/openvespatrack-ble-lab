    fun describe(context: Context, raw: String): String = describe(context, raw, 0)

    private fun describe(context: Context, raw: String, depth: Int): String {
        exact[raw]?.let { return context.getString(it) }
        if (depth >= 8) return raw
        for (pattern in patterns) {
            val match = pattern.regex.matchEntire(raw) ?: continue
            val arguments = match.groupValues.drop(1).map {
                if (pattern.translateArguments) describe(context, it, depth + 1) else it
            }.toTypedArray()
            return context.getString(pattern.resource, *arguments)
        }
        // A repository warning can prepend a filename/ID to a known diagnostic.
        val delimiter = raw.indexOf(": ")
        if (delimiter > 0) {
            val detail = raw.substring(delimiter + 2)
            val translated = describe(context, detail, depth + 1)
            if (translated != detail) return raw.substring(0, delimiter + 2) + translated
        }
        return raw
    }
